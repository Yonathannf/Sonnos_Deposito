-- ---------- Helpers ---------------------------------------------------
-- puede('pedidos')            -> tiene al menos 'ver'
-- puede('pedidos','editar')   -> tiene 'editar'
create or replace function public.puede(p_panel text, p_minimo text default 'ver')
returns boolean language sql stable security definer set search_path = public as $$
  select case p_minimo
    when 'editar' then public.nivel_panel(p_panel) = 'editar'
    else public.nivel_panel(p_panel) in ('ver','editar')
  end;
$$;

-- Auditoría: ahora ignora las operaciones sin usuario (cargas masivas desde el SQL Editor)
-- y reconoce tablas con clave 'sku'.
create or replace function public.trg_auditar()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_nombre text; v_id text; k text; v_old jsonb; v_new jsonb;
begin
  if auth.uid() is null then return null; end if;   -- carga masiva / sistema: sin auditoría
  select nombre into v_nombre from perfiles where id = auth.uid();

  if tg_op = 'INSERT' then
    v_new := to_jsonb(new);
    v_id  := coalesce(v_new->>'id', v_new->>'sku', v_new->>'rol_id', '?') ||
             case when tg_table_name = 'permisos_rol' then ':' || (v_new->>'panel') else '' end;
    insert into registro_auditoria(usuario_id, usuario_nombre, entidad, entidad_id, accion, descripcion)
    values (auth.uid(), v_nombre, tg_table_name, v_id, 'crear', left(v_new::text, 2000));
    return null;
  elsif tg_op = 'UPDATE' then
    v_old := to_jsonb(old); v_new := to_jsonb(new);
    v_id  := coalesce(v_new->>'id', v_new->>'sku', v_new->>'rol_id', '?') ||
             case when tg_table_name = 'permisos_rol' then ':' || (v_new->>'panel') else '' end;
    for k in select jsonb_object_keys(v_new) loop
      if v_old->k is distinct from v_new->k then
        insert into registro_auditoria(usuario_id, usuario_nombre, entidad, entidad_id, accion, campo, valor_anterior, valor_nuevo)
        values (auth.uid(), v_nombre, tg_table_name, v_id, 'editar', k, v_old->>k, v_new->>k);
      end if;
    end loop;
    return null;
  else
    v_old := to_jsonb(old);
    v_id  := coalesce(v_old->>'id', v_old->>'sku', v_old->>'rol_id', '?') ||
             case when tg_table_name = 'permisos_rol' then ':' || (v_old->>'panel') else '' end;
    insert into registro_auditoria(usuario_id, usuario_nombre, entidad, entidad_id, accion, descripcion)
    values (auth.uid(), v_nombre, tg_table_name, v_id, 'borrar', left(v_old::text, 2000));
    return null;
  end if;
end $$;

-- Configuración clave/valor (plazos, tolerancias)
create table if not exists public.configuracion (
  clave text primary key,
  valor text not null
);
insert into public.configuracion (clave, valor) values
  ('plazo_armado_dias',          '4'),   -- un armado es EFICIENTE si tarda menos de estos días
  ('plazo_entrega_dias',         '3'),   -- una entrega es EFICIENTE si tarda menos de estos días
  ('plazo_despacho_default_dias','7'),   -- plazo de despacho por defecto de un pedido
  ('tolerancia_inventario_pct',  '3')    -- tolerancia del control de inventario
on conflict (clave) do nothing;

create or replace function public.cfg_int(p_clave text, p_default int)
returns int language sql stable security definer set search_path = public as $$
  select coalesce((select valor::numeric::int from configuracion where clave = p_clave), p_default);
$$;
create or replace function public.cfg_num(p_clave text, p_default numeric)
returns numeric language sql stable security definer set search_path = public as $$
  select coalesce((select valor::numeric from configuracion where clave = p_clave), p_default);
$$;

