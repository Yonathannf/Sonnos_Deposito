-- Un pedido pasa a 'Armado' => queda la fecha de armado.
create or replace function public.trg_pedido_estado()
returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' and old.estado = 'Impreso' and new.estado = 'Entregado' then
    raise exception 'No se puede entregar un pedido que todavía no fue armado';
  end if;
  if new.estado in ('Armado','Entregado') and new.fecha_armado is null then
    new.fecha_armado := current_date;
  end if;
  return new;
end $$;
drop trigger if exists pedido_estado on public.pedidos;
create trigger pedido_estado before insert or update on public.pedidos
  for each row execute function public.trg_pedido_estado();

-- Registro de armados (reemplaza la PLANILLA DE ARMADO)
create table if not exists public.armados (
  id                 integer generated by default as identity primary key,
  fecha              date not null,
  nro_cliente        text,
  nro_pedido         text,
  prioridad          text not null default 'NORMAL' check (prioridad in ('NORMAL','URGENTE','ESTACIONADO')),
  despacho           text not null,
  operario_id        integer references public.operarios(id) on delete set null,
  bultos             integer check (bultos is null or bultos >= 0),
  pallets            integer check (pallets is null or pallets >= 0),
  carro              integer check (carro is null or carro >= 0),
  tiempo_min         integer check (tiempo_min is null or tiempo_min >= 0),
  estado             text not null default 'FINALIZADO' check (estado in ('EN PROCESO','FINALIZADO')),
  fecha_finalizacion date,
  fecha_entrega      date,
  observaciones      text,
  pedido_id          integer references public.pedidos(id) on delete set null,
  creado_en          timestamptz not null default now(),
  creado_por         uuid default auth.uid() references auth.users(id) on delete set null,
  constraint armados_fechas_ok check (
    (fecha_finalizacion is null or fecha_finalizacion >= fecha) and
    (fecha_entrega is null or fecha_finalizacion is null or fecha_entrega >= fecha_finalizacion))
);
create index if not exists idx_armados_fecha    on public.armados (fecha);
create index if not exists idx_armados_operario on public.armados (operario_id);
create index if not exists idx_armados_pedido   on public.armados (nro_pedido);

-- ---------- Vistas calculadas (respetan RLS del usuario) ---------------
-- Eficiencia de entrega CORREGIDA: días entre finalización y entrega.
-- (La fórmula original del Excel restaba al revés y daba siempre EFICIENTE.)
create or replace view public.armados_calc with (security_invoker = true) as
select a.*,
  o.nombre as operario,
  (a.fecha_finalizacion - a.fecha) as dias_armado,
  case when a.fecha_finalizacion is null then null
       when (a.fecha_finalizacion - a.fecha) < public.cfg_int('plazo_armado_dias', 4)
       then 'EFICIENTE' else 'FUERA DE PLAZO' end as ef_armado,
  (a.fecha_entrega - a.fecha_finalizacion) as dias_entrega,
  case when a.fecha_entrega is null or a.fecha_finalizacion is null then null
       when (a.fecha_entrega - a.fecha_finalizacion) < public.cfg_int('plazo_entrega_dias', 3)
       then 'EFICIENTE' else 'FUERA DE PLAZO' end as ef_entrega
from public.armados a
left join public.operarios o on o.id = a.operario_id;

create or replace view public.pedidos_calc with (security_invoker = true) as
select p.*,
  c.nombre as cliente_nombre, c.numero_cliente as cliente_numero, c.localidad as cliente_localidad,
  t.nombre as transporte_nombre, o.nombre as operario_nombre,
  (p.fecha_impreso + coalesce(p.plazo_armado_dias, public.cfg_int('plazo_despacho_default_dias', 7))) as fecha_estimada_despacho,
  case when p.dia_a_despachar is null or p.fecha_impreso is null then null
       when p.dia_a_despachar <= p.fecha_impreso + coalesce(p.plazo_armado_dias, public.cfg_int('plazo_despacho_default_dias', 7))
       then 'CUMPLE' else 'NO CUMPLE' end as cumple_plazo
from public.pedidos p
left join public.clientes c on c.id = p.cliente_id
left join public.transportes t on t.id = p.transporte_id
left join public.operarios o on o.id = p.operario_id;

-- ---------- Indicadores de armado (reemplaza la solapa INDICADOR) ------
create or replace function public.indicadores_armado(p_desde date, p_hasta date)
returns jsonb language sql stable security invoker set search_path = public as $$
  with a as (
    select * from armados_calc where fecha between p_desde and p_hasta
  )
  select jsonb_build_object(
    'totales', (select jsonb_build_object(
        'pedidos', count(*), 'bultos', coalesce(sum(bultos),0), 'pallets', coalesce(sum(pallets),0),
        'carros', coalesce(sum(carro),0), 'minutos', coalesce(sum(tiempo_min),0),
        'min_promedio', round(avg(tiempo_min)::numeric, 1),
        'armado_eficiente', count(*) filter (where ef_armado = 'EFICIENTE'),
        'armado_medido',    count(*) filter (where ef_armado is not null),
        'entrega_eficiente',count(*) filter (where ef_entrega = 'EFICIENTE'),
        'entrega_medida',   count(*) filter (where ef_entrega is not null)) from a),
    'por_despacho', coalesce((select jsonb_agg(x order by x->>'despacho') from (
        select jsonb_build_object('despacho', despacho, 'pedidos', count(*),
          'bultos', coalesce(sum(bultos),0), 'pallets', coalesce(sum(pallets),0),
          'carros', coalesce(sum(carro),0), 'minutos', coalesce(sum(tiempo_min),0)) x
        from a group by despacho) s), '[]'::jsonb),
    'por_operario', coalesce((select jsonb_agg(x order by (x->>'pedidos')::int desc) from (
        select jsonb_build_object('operario', coalesce(operario,'(sin asignar)'), 'pedidos', count(*),
          'bultos', coalesce(sum(bultos),0), 'minutos', coalesce(sum(tiempo_min),0),
          'min_promedio', round(avg(tiempo_min)::numeric,1),
          'eficiente', count(*) filter (where ef_armado = 'EFICIENTE'),
          'medido', count(*) filter (where ef_armado is not null)) x
        from a group by operario) s), '[]'::jsonb),
    'por_dia', coalesce((select jsonb_agg(x order by x->>'fecha') from (
        select jsonb_build_object('fecha', fecha, 'pedidos', count(*), 'bultos', coalesce(sum(bultos),0)) x
        from a group by fecha) s), '[]'::jsonb)
  );
$$;

