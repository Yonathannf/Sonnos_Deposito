-- ---------- Conexión armado -> pedido ----------------------------------
-- Al registrar un armado se vincula al pedido por número y el pedido pasa a 'Armado'
-- con los datos reales (bultos, pallets, carro, operario). Corre con permisos del sistema
-- para que un operario de armado no necesite permiso de edición sobre pedidos.
create or replace function public.trg_armado_sync()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.pedido_id is null and new.nro_pedido is not null then
    select id into new.pedido_id from pedidos where nro_pedido = new.nro_pedido;
  end if;
  return new;
end $$;
drop trigger if exists armado_sync_b on public.armados;
create trigger armado_sync_b before insert on public.armados
  for each row execute function public.trg_armado_sync();

create or replace function public.trg_armado_pedido()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.pedido_id is not null and new.estado = 'FINALIZADO' then
    update pedidos set
      estado        = case when estado = 'Impreso' then 'Armado' else estado end,
      bultos        = coalesce(new.bultos, bultos),
      pallets       = coalesce(new.pallets, pallets),
      carro_cajon   = coalesce(new.carro::text, carro_cajon),
      operario_id   = coalesce(new.operario_id, operario_id),
      fecha_armado  = coalesce(new.fecha_finalizacion, fecha_armado, current_date)
    where id = new.pedido_id;
  end if;
  return null;
end $$;
drop trigger if exists armado_sync_a on public.armados;
create trigger armado_sync_a after insert on public.armados
  for each row execute function public.trg_armado_pedido();
