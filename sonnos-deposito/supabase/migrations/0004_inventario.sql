-- =====================================================================
-- Sonnos Depósito · Etapa 6 · Inventario físico (conteos y precisión)
-- Ejecutar DESPUÉS de 0003_stock.sql.
-- Regla del Excel "Precisión de inventario": diferencia = conteo - sistema;
-- es ACIERTO si la diferencia está dentro de ±tolerancia (3%) del sistema.
-- "Sistema" = MayoGym + Central + Anticipada + Outlet (físico) al momento del conteo.
-- =====================================================================
create table if not exists public.conteos (
  id          integer generated by default as identity primary key,
  fecha       date not null default current_date,
  nombre      text not null,
  estado      text not null default 'Abierto' check (estado in ('Abierto','Cerrado')),
  observaciones text,
  creado_en   timestamptz not null default now(),
  creado_por  uuid default auth.uid() references auth.users(id) on delete set null,
  cerrado_en  timestamptz,
  cerrado_por uuid references auth.users(id) on delete set null
);

create table if not exists public.conteo_items (
  id          integer generated by default as identity primary key,
  conteo_id   integer not null references public.conteos(id) on delete cascade,
  sku         text not null,
  descripcion text,
  contado     int not null check (contado >= 0),
  sistema     int not null default 0,                            -- foto del stock del sistema al contar (lo completa el trigger)
  ajuste      text check (ajuste in ('pendiente','cargado','descartado')),
  ajuste_obs  text,
  creado_en   timestamptz not null default now(),
  creado_por  uuid default auth.uid() references auth.users(id) on delete set null,
  unique (conteo_id, sku)
);
create index if not exists idx_conteo_items_sku on public.conteo_items (sku);

-- Completa descripción y "sistema" desde el stock importado. Exige que el SKU exista.
create or replace function public.trg_conteo_item_antes()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_estado text; p record;
begin
  select estado into v_estado from conteos where id = new.conteo_id;
  if v_estado = 'Cerrado' and auth.uid() is not null then
    raise exception 'El conteo está cerrado: no se pueden agregar artículos';
  end if;
  if tg_op = 'INSERT' then
    if auth.uid() is null and new.sistema is not null then return new; end if;   -- carga histórica (SQL Editor)
    select descripcion, stk_control into p from stock_productos where sku = new.sku;
    if not found then
      raise exception 'El código % no existe en el stock importado (importá el LISTADO o revisá el código)', new.sku;
    end if;
    new.descripcion := coalesce(new.descripcion, p.descripcion);
    new.sistema := p.stk_control;
  end if;
  return new;
end $$;
drop trigger if exists conteo_item_antes on public.conteo_items;
create trigger conteo_item_antes before insert on public.conteo_items
  for each row execute function public.trg_conteo_item_antes();

-- Un conteo cerrado no se modifica ni se borra (solo se gestionan los ajustes, vía función).
create or replace function public.trg_conteo_inmutable()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_estado text;
begin
  select estado into v_estado from conteos where id = coalesce(new.conteo_id, old.conteo_id);
  if v_estado = 'Cerrado' and current_setting('app.ajuste', true) is distinct from '1' then
    raise exception 'El conteo está cerrado y no se puede modificar';
  end if;
  -- En un conteo abierto solo se puede corregir la cantidad contada:
  -- el stock "sistema" es una foto y los ajustes los gestionan las funciones del sistema.
  if tg_op = 'UPDATE' and auth.uid() is not null and current_setting('app.ajuste', true) is distinct from '1' then
    if new.sistema is distinct from old.sistema or new.sku is distinct from old.sku
       or new.conteo_id is distinct from old.conteo_id or new.descripcion is distinct from old.descripcion
       or new.ajuste is distinct from old.ajuste or new.ajuste_obs is distinct from old.ajuste_obs then
      raise exception 'Solo se puede corregir la cantidad contada';
    end if;
  end if;
  return coalesce(new, old);
end $$;
drop trigger if exists conteo_item_inmutable on public.conteo_items;
create trigger conteo_item_inmutable before update or delete on public.conteo_items
  for each row execute function public.trg_conteo_inmutable();

-- Cierre: los artículos fuera de tolerancia quedan con ajuste 'pendiente'.
create or replace function public.cerrar_conteo(p_id int)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_tol numeric; v_n int; v_pend int;
begin
  if not public.puede('inventario','editar') then raise exception 'Sin permiso'; end if;
  if not exists (select 1 from conteos where id = p_id and estado = 'Abierto') then raise exception 'El conteo no existe o ya está cerrado'; end if;
  select count(*) into v_n from conteo_items where conteo_id = p_id;
  if v_n = 0 then raise exception 'No se puede cerrar un conteo sin artículos'; end if;
  v_tol := public.cfg_num('tolerancia_inventario_pct', 3) / 100;
  perform set_config('app.ajuste','1',true);
  update conteo_items set ajuste = 'pendiente'
    where conteo_id = p_id and (contado - sistema) <> 0
      and ((contado - sistema) < -(sistema * v_tol) or (contado - sistema) > (sistema * v_tol));
  get diagnostics v_pend = row_count;
  update conteos set estado = 'Cerrado', cerrado_en = now(), cerrado_por = auth.uid() where id = p_id;
  perform set_config('app.ajuste','0',true);
  return jsonb_build_object('articulos', v_n, 'ajustes_pendientes', v_pend);
end $$;

-- Gestión de ajustes (los resuelve quien administra el stock: jefe / dueño)
create or replace function public.resolver_ajuste(p_item int, p_estado text, p_obs text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.puede('stock','editar') then raise exception 'Solo quien administra el stock puede resolver ajustes'; end if;
  if p_estado not in ('cargado','descartado') then raise exception 'Estado de ajuste inválido'; end if;
  if not exists (select 1 from conteo_items where id = p_item and ajuste = 'pendiente') then raise exception 'El ajuste no está pendiente'; end if;
  perform set_config('app.ajuste','1',true);
  update conteo_items set ajuste = p_estado, ajuste_obs = p_obs where id = p_item;
  perform set_config('app.ajuste','0',true);
  perform public.registrar_auditoria('conteo_items', p_item::text, 'editar', 'Ajuste ' || p_estado || coalesce(': ' || p_obs, ''));
end $$;

-- Vistas con el cálculo del Excel
create or replace view public.conteo_items_calc with (security_invoker = true) as
select i.*, c.fecha as conteo_fecha, c.nombre as conteo_nombre,
  (i.contado - i.sistema) as dif,
  case when i.sistema > 0 then round(((i.contado - i.sistema)::numeric / i.sistema) * 100, 1) end as dif_pct,
  case
    when i.contado = i.sistema then 'OK'
    when (i.contado - i.sistema) < -(i.sistema * public.cfg_num('tolerancia_inventario_pct', 3) / 100) then 'FALTANTE'
    when (i.contado - i.sistema) >  (i.sistema * public.cfg_num('tolerancia_inventario_pct', 3) / 100) then 'SOBRANTE'
    else 'DENTRO DE TOLERANCIA' end as resultado
from public.conteo_items i
join public.conteos c on c.id = i.conteo_id;

create or replace view public.conteos_resumen with (security_invoker = true) as
select c.*,
  count(i.id) as articulos,
  count(i.id) filter (where i.resultado in ('OK','DENTRO DE TOLERANCIA')) as aciertos,
  count(i.id) filter (where i.resultado = 'FALTANTE') as faltantes,
  count(i.id) filter (where i.resultado = 'SOBRANTE') as sobrantes,
  count(i.id) filter (where i.ajuste = 'pendiente') as ajustes_pendientes,
  case when count(i.id) > 0 then round(100.0 * count(i.id) filter (where i.resultado in ('OK','DENTRO DE TOLERANCIA')) / count(i.id), 1) end as precision_pct
from public.conteos c
left join public.conteo_items_calc i on i.conteo_id = c.id
group by c.id;

-- Auditoría y RLS
do $$ declare t text; begin
  foreach t in array array['conteos','conteo_items'] loop
    execute format('drop trigger if exists aud_%1$s on public.%1$s', t);
    execute format('create trigger aud_%1$s after insert or update or delete on public.%1$s for each row execute function public.trg_auditar()', t);
    execute format('alter table public.%I enable row level security', t);
  end loop; end $$;

drop policy if exists conteos_sel on public.conteos;
create policy conteos_sel on public.conteos for select to authenticated using (public.puede('inventario'));
drop policy if exists conteos_ins on public.conteos;
create policy conteos_ins on public.conteos for insert to authenticated with check (public.puede('inventario','editar'));
drop policy if exists conteos_upd on public.conteos;
create policy conteos_upd on public.conteos for update to authenticated
  using (public.puede('inventario','editar') and estado = 'Abierto') with check (public.puede('inventario','editar'));
