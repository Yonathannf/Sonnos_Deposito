-- El stock del insumo solo cambia por movimientos (nunca se edita a mano).
create or replace function public.trg_insumo_mov()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_stock int; v_delta int;
begin
  select stock_actual into v_stock from insumos where id = new.insumo_id for update;
  v_delta := case new.tipo when 'consumo' then -new.cantidad else new.cantidad end;
  if v_stock + v_delta < 0 then
    raise exception 'Stock insuficiente: hay % y se quieren sacar %', v_stock, -v_delta;
  end if;
  new.stock_resultante := v_stock + v_delta;
  new.responsable := coalesce(new.responsable, (select nombre from perfiles where id = auth.uid()));
  perform set_config('app.insumo_mov', '1', true);
  update insumos set stock_actual = new.stock_resultante, actualizado_en = now() where id = new.insumo_id;
  perform set_config('app.insumo_mov', '0', true);
  return new;
end $$;
drop trigger if exists insumo_mov_antes on public.insumo_movimientos;
create trigger insumo_mov_antes before insert on public.insumo_movimientos for each row execute function public.trg_insumo_mov();

create or replace function public.trg_insumo_guard()
returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if new.stock_actual <> 0 and auth.uid() is not null then
      raise exception 'El stock inicial se carga como un ingreso, no directamente';
    end if;
  elsif new.stock_actual is distinct from old.stock_actual and current_setting('app.insumo_mov', true) is distinct from '1' and auth.uid() is not null then
    raise exception 'El stock de un insumo solo cambia con ingresos, consumos o ajustes';
  end if;
  return new;
end $$;
drop trigger if exists insumo_guard on public.insumos;
create trigger insumo_guard before insert or update on public.insumos for each row execute function public.trg_insumo_guard();

create or replace function public.recibir_solicitud(p_id int, p_cantidad int)
returns void language plpgsql security definer set search_path = public as $$
declare s record;
begin
  if not public.puede('insumos','editar') then raise exception 'Sin permiso'; end if;
  select * into s from solicitudes_compra where id = p_id for update;
  if not found or s.estado <> 'Pendiente' then raise exception 'La solicitud no está pendiente'; end if;
  if p_cantidad is null or p_cantidad <= 0 then raise exception 'Cantidad recibida inválida'; end if;
  insert into insumo_movimientos (insumo_id, tipo, cantidad, solicitud_id, observaciones)
    values (s.insumo_id, 'ingreso', p_cantidad, p_id, 'Recepción de solicitud de compra #' || p_id);
  update solicitudes_compra set estado = 'Recibida', fecha_recepcion_real = current_date where id = p_id;
end $$;

create or replace view public.insumos_calc with (security_invoker = true) as
select i.*,
  case
    when i.stock_minimo is null then 'SIN MÍNIMO'
    when i.stock_actual < i.stock_minimo then 'CRITICO'
    when i.stock_maximo is not null and i.stock_maximo > i.stock_minimo
         then case when i.stock_actual < i.stock_minimo + 0.2 * (i.stock_maximo - i.stock_minimo) then 'ALERTA' else 'OK' end
    else case when i.stock_actual = i.stock_minimo then 'ALERTA' else 'OK' end
  end as estado,
  case when i.stock_minimo is null then null else greatest(0, i.stock_minimo - i.stock_actual) end as faltante_para_minimo,
  case when i.stock_minimo is null or i.stock_maximo is null then null
       when i.stock_actual < i.stock_minimo then greatest(0, i.stock_maximo - i.stock_actual) else 0 end as cantidad_a_pedir,
  (select count(*) from public.solicitudes_compra s where s.insumo_id = i.id and s.estado = 'Pendiente') as solicitudes_pendientes
from public.insumos i;

