create view public.stock_calc with (security_invoker = true) as
select p.*,
  (p.stk + p.ajuste_local) as stock_actual,
  case when p.minimo is null then 'SIN MÍNIMO'
       when (p.stk + p.ajuste_local) < p.minimo then 'ALERTA' else 'OK' end as estado
from public.stock_productos p;

