    insert into storage.buckets (id, name, public) values ('recepciones', 'recepciones', false) on conflict (id) do nothing;
    execute 'drop policy if exists recepciones_fotos_sel on storage.objects';
    execute $p$create policy recepciones_fotos_sel on storage.objects for select to authenticated
      using (bucket_id = 'recepciones' and public.puede('recepcion'))$p$;
    execute 'drop policy if exists recepciones_fotos_ins on storage.objects';
    execute $p$create policy recepciones_fotos_ins on storage.objects for insert to authenticated
      with check (bucket_id = 'recepciones' and public.puede('recepcion','editar'))$p$;
  end if;
end $$;
