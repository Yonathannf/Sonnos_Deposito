create or replace function public.trg_recepcion_item()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_estado text; p record;
begin
  select estado into v_estado from recepciones where id = coalesce(new.recepcion_id, old.recepcion_id);
  if v_estado = 'Confirmada' and auth.uid() is not null then
    raise exception 'La recepción está confirmada y no se puede modificar';
  end if;
  if tg_op = 'DELETE' then return old; end if;
  if tg_op = 'INSERT' and auth.uid() is not null then
    select descripcion into p from stock_productos where sku = new.sku;
    if not found then
      raise exception 'El código % no existe en el stock importado (importá el LISTADO o revisá el código)', new.sku;
    end if;
    new.descripcion := coalesce(new.descripcion, p.descripcion);
  end if;
  return new;
end $$;
drop trigger if exists recepcion_item_trg on public.recepcion_items;
create trigger recepcion_item_trg before insert or update or delete on public.recepcion_items
  for each row execute function public.trg_recepcion_item();

create or replace function public.confirmar_recepcion(p_id int)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r record; it record; v_dif boolean := false; v_n int; v_total int := 0;
begin
  if not public.puede('recepcion','editar') then raise exception 'Sin permiso'; end if;
  select * into r from recepciones where id = p_id for update;
  if not found then raise exception 'Recepción inexistente'; end if;
  if r.estado <> 'Borrador' then raise exception 'La recepción ya está confirmada'; end if;
  select count(*) into v_n from recepcion_items where recepcion_id = p_id;
  if v_n = 0 then raise exception 'Cargá al menos un artículo antes de confirmar'; end if;
  for it in select * from recepcion_items where recepcion_id = p_id loop
    if it.recibido <> it.esperado or it.danado > 0 then
      v_dif := true;
      if it.observaciones is null or btrim(it.observaciones) = '' then
        raise exception 'El artículo % tiene diferencias o daños: indicá una observación', it.sku;
      end if;
    end if;
  end loop;
  for it in select * from recepcion_items where recepcion_id = p_id loop
    if it.recibido - it.danado > 0 then
      insert into stock_movimientos (sku, tipo, cantidad, ref_tabla, ref_id, observaciones)
        values (it.sku, 'recepcion', it.recibido - it.danado, 'recepciones', p_id,
                'Remito ' || r.nro_remito || ' · ' || r.proveedor);
      v_total := v_total + (it.recibido - it.danado);
    end if;
    if it.ubicacion is not null and btrim(it.ubicacion) <> '' then
      update stock_productos set ubicacion = btrim(it.ubicacion) where sku = it.sku;
    end if;
  end loop;
  update recepciones set estado = 'Confirmada', con_diferencias = v_dif, confirmado_en = now(), confirmado_por = auth.uid() where id = p_id;
  perform public.registrar_auditoria('recepciones', p_id::text, 'otro',
    'Recepción confirmada: ' || v_n || ' artículos, ' || v_total || ' unidades al stock' || case when v_dif then ' (con diferencias)' else '' end);
  return jsonb_build_object('articulos', v_n, 'unidades', v_total, 'con_diferencias', v_dif);
end $$;

-- ---------- Tareas del depósito -----------------------------------------
create table if not exists public.tareas (
  id              integer generated by default as identity primary key,
  titulo          text not null,
  descripcion     text,
  sector          text,
  prioridad       text not null default 'Media' check (prioridad in ('Alta','Media','Baja')),
  estado          text not null default 'Pendiente' check (estado in ('Pendiente','En curso','Finalizada','Cancelada')),
  operario_id     integer references public.operarios(id) on delete set null,
  fecha_limite    date,
  inicio          timestamptz,
  fin             timestamptz,
  creado_en       timestamptz not null default now(),
  creado_por      uuid default auth.uid() references auth.users(id) on delete set null,
  constraint tarea_fin_ok check (fin is null or inicio is null or fin >= inicio)
);
create index if not exists idx_tareas_estado on public.tareas (estado, fecha_limite);

create or replace function public.trg_tarea()
returns trigger language plpgsql as $$
begin
  if new.estado = 'En curso' and new.inicio is null then new.inicio := now(); end if;
  if new.estado = 'Finalizada' then
    new.inicio := coalesce(new.inicio, now());
    new.fin := coalesce(new.fin, now());
  end if;
  if tg_op = 'UPDATE' and old.estado in ('Finalizada','Cancelada') and new.estado <> old.estado then
    raise exception 'Una tarea % no se puede reabrir', lower(old.estado);
  end if;
  return new;
end $$;
drop trigger if exists tarea_trg on public.tareas;
create trigger tarea_trg before insert or update on public.tareas for each row execute function public.trg_tarea();

create or replace view public.tareas_calc with (security_invoker = true) as
select t.*, o.nombre as operario,
  case when t.inicio is not null and t.fin is not null then round(extract(epoch from (t.fin - t.inicio)) / 60)::int end as minutos,
  case when t.estado in ('Pendiente','En curso') and t.fecha_limite < current_date then true else false end as vencida,
  case when t.estado = 'Finalizada' and t.fecha_limite is not null
       then (t.fin at time zone 'America/Argentina/Buenos_Aires')::date <= t.fecha_limite end as a_tiempo
from public.tareas t left join public.operarios o on o.id = t.operario_id;

